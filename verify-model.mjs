import {availableDays} from './lib/model.ts';
const now=Date.parse('2026-12-30T00:00:00+09:00');
const busy=[event('2026-12-31T09:00:00+09:00','2026-12-31T18:00:00+09:00')];
assert.deepEqual(availableDays(busy,'2026-12-30','2027-01-01',60,30,now).map(d=>d.date),['2026-12-30','2027-01-01']);
assert.equal(availableDays([], '2027-01-01','2027-01-01',60,30,now).length,1);
assert.throws(()=>availableDays([],'2027-01-02','2027-01-01',60,30,now));
assert.throws(()=>availableDays([],'','2027-01-01',60,30,now));
assert.throws(()=>availableDays([],'2027-02-30','2027-03-01',60,30,now));
assert.throws(()=>availableDays([],'2027-01-01','2027-04-04',60,30,now));
assert.equal(availableDays([],'2027-01-01','2027-04-03',60,30,now).length,93);
const current=Date.parse('2026-12-30T15:07:00+09:00');
const todaySlots=availableDays([],'2026-12-29','2026-12-30',60,30,current);
assert.equal(todaySlots.length,1);assert.equal(todaySlots[0].slots[0][0],Date.parse('2026-12-30T15:15:00+09:00'));
assert.equal(availableDays([],'2026-12-30','2026-12-30',60,30,Date.parse('2026-12-30T17:15:00+09:00')).length,0);
const overnight=[event('2026-12-30T17:00:00+09:00','2027-01-01T10:00:00+09:00')];
const overnightDays=availableDays(overnight,'2026-12-30','2027-01-01',60,30,now);
assert.deepEqual(overnightDays.map(d=>d.date),['2026-12-30','2027-01-01']);
assert.equal(overnightDays[1].slots[0][0],Date.parse('2027-01-01T10:30:00+09:00'));
